function faqSection(faqs) {
  return { kicker: 'إجابات', h2: 'الأسئلة الشائعة', body: '', faqs };
}

function gamePage(g) {
  const others = site.games
    .filter((x) => x.slug !== g.slug)
    .slice(0, 5)
    .map((x) => ({ label: 'زخرفة اسماء ' + x.name, href: `/العاب/${x.slug}/`, desc: x.desc }));
  return {
    path: `العاب/${g.slug}`,
    title: g.title,
    description: g.desc,
    breadcrumb: [
      { label: 'الرئيسية', href: '/' },
      { label: 'الألعاب', href: '/العاب/' },
      { label: g.name },
    ],
    kicker: 'زخرفة أسماء الألعاب',
    h1: g.h1,
    intro: [g.hook, g.mechanic],
    tool: { kind: 'decorator', defaultFilter: 'game', placeholder: `اكتب اسمك لزخرفته لـ${g.name}…` },
    sections: [
      {
        kicker: 'خطوة بخطوة',
        h2: `كيف تغيّر اسمك في ${g.name}`,
        body: h.steps(g.steps),
        wide: true,
      },
      {
        kicker: 'الأنماط',
        h2: `أنماط تناسب ${g.name}`,
        sub: 'مرتبة من الأعلى قبولاً داخل اللعبة إلى الأكثر استهلاكاً للأحرف.',
        body: h.styleTable([...(g.tableExtra || []), ...SHARED_TABLE]),
        wide: true,
      },
      { kicker: 'نصائح', h2: `نصائح لاسم ${g.name} ناجح`, body: h.ulist(g.tips) },
      { kicker: 'تجنّب', h2: `أخطاء شائعة في ${g.name}`, body: h.ulist(g.mistakes) },
      {
        kicker: 'تعمّق',
        h2: `تفاصيل تخصّ ${g.name}`,
        body: g.deep.map((d) => `<h3>${d.h}</h3>\n<p>${d.p}</p>`).join('\n'),
      },
      faqSection(g.faqs),
    ],
    faqs: g.faqs,
    related: {
      title: 'ألعاب أخرى',
      items: [...others, { label: 'مولّد الزخرفة الرئيسي', href: '/مولد-اسماء-مزخرفة/', desc: 'كل الأنماط والإطارات في مكان واحد.' }],
    },
  };
}


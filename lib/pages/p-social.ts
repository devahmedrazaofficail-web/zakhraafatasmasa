import * as h from '../html';
import { site } from '../site';
import type { Faq, PageData } from '../types';
import type { Step } from '../html';

interface SocialEntry {
  slug: string; name: string; title: string; desc: string; h1: string;
  hook: string; rules: string;
  steps: Step[];
  fields: string[];
  tips: string[]; mistakes: string[];
  faqs: Faq[];
}

// صفحات التواصل الاجتماعي (10 صفحات)

function socialPage(s: SocialEntry): PageData {
  const others = site.socials
    .filter((x) => x.slug !== s.slug)
    .slice(0, 5)
    .map((x) => ({ label: 'زخرفة اسماء ' + x.name, href: `/تواصل-اجتماعي/${x.slug}/`, desc: x.desc }));
  return {
    path: `تواصل-اجتماعي/${s.slug}`,
    title: s.title,
    description: s.desc,
    breadcrumb: [
      { label: 'الرئيسية', href: '/' },
      { label: 'التواصل الاجتماعي', href: '/تواصل-اجتماعي/' },
      { label: s.name },
    ],
    kicker: 'زخرفة حسابات التواصل',
    h1: s.h1,
    intro: [s.hook, s.rules],
    tool: { kind: 'decorator', defaultFilter: 'all', placeholder: 'اكتب اسمك لزخرفته…' },
    sections: [
      {
        kicker: 'خطوة بخطوة',
        h2: `كيف تضع اسمك المزخرف في ${s.name}`,
        body: h.steps(s.steps),
        wide: true,
      },
      { kicker: 'قواعد المنصة', h2: `ما الذي يقبل الزخرفة في ${s.name}؟`, body: h.paras(s.fields) },
      { kicker: 'نصائح', h2: `نصائح لاسم ${s.name} مميز`, body: h.ulist(s.tips) },
      { kicker: 'تجنّب', h2: 'أخطاء شائعة', body: h.ulist(s.mistakes) },
      {
        kicker: 'إجابات',
        h2: 'الأسئلة الشائعة',
        body: '',
        faqs: s.faqs,
      },
    ],
    faqs: s.faqs,
    related: {
      title: 'منصات أخرى',
      items: [...others, { label: 'مكتبة الرموز', href: '/رموز/', desc: 'رموز جاهزة للنسخ لتزيين اسمك.' }],
    },
  };
}

